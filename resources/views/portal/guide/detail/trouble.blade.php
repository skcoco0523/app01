    <p class="lead fs-6 text-secondary mb-4">スマートリモコンがオフライン表示になった際や、操作ボタンを押しても家電が反応しない場合のチェックポイントです。</p>
    <h2 class="fs-6 fw-bold border-bottom pb-2 mt-4 text-primary"><i class="fa-solid fa-network-wired me-2"></i>1. Wi-Fi通信とIPアドレス固定の推奨</h2>
    <p>ルーターの再起動でIPアドレスが変更され、一時的に切断されることがあります。<br>ルーター管理画面からスマートリモコンにIPアドレスを固定割り当てすると通信が非常に安定します。</p>
    <h2 class="fs-6 fw-bold border-bottom pb-2 mt-4 text-primary"><i class="fa-solid fa-eye-slash me-2"></i>2. 物理的な遮蔽物と赤外線照射角度</h2>
    <p>赤外線は壁や天井に反射して届きますが、家具や棚などの遮蔽物があると電波強度が低下します。<br>家電の受光部が見通せる位置に端末を配置し直してください。</p>
