    <h2 class="fs-6 fw-bold border-bottom pb-2 mt-4 text-primary"><i class="fa-solid fa-share-nodes me-2"></i>2. リモコン・メモの共有と権限変更</h2>
    <p>各アイテムの詳細画面にある「共有」ボタンから、共有したいフレンドを選択します。<br>閲覧のみを許可するか、編集・家電の操作権限まで許可するかをいつでもワンタップで切り替えられます。</p>
