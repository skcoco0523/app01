<script>
    const slides = document.querySelectorAll('.slide');
    const pageBtns = document.querySelectorAll('.page-btn');
    const baby = document.getElementById('baby');
    const progress = document.getElementById('progress');
    const modeBtn = document.getElementById('modeBtn');
    const modeIcon = document.getElementById('modeIcon');
    const modeText = document.getElementById('modeText');
    const bgm = document.getElementById('bgm');
    const bgmBtn = document.getElementById('bgmBtn');
    const bgmText = document.getElementById('bgmText');
    const startOverlay = document.getElementById('startOverlay');

    let currentSlide = 0;
    let isAuto = false;
    let isBgmEnabled = true;

    const SLIDE_DURATION = 7500; // 1枚あたりの表示時間（7.5秒）
    let autoTimeoutId = null;

    function startPresentation() {
        document.body.classList.add('started');
        if (startOverlay) {
            startOverlay.classList.add('hidden');
        }
        setAutoMode(true);
    }

    function tryPlayBGM() {
        if (isBgmEnabled && bgm && bgm.paused) {
            bgm.volume = 0.3;
            bgm.play().catch(e => {
                console.log('再生エラー:', e);
            });
        }
    }

    function toggleBGM() {
        isBgmEnabled = !isBgmEnabled;
        if (isBgmEnabled) {
            bgmBtn.classList.add('active');
            bgmText.textContent = 'BGM ON';
            if (isAuto) tryPlayBGM();
        } else {
            bgmBtn.classList.remove('active');
            bgmText.textContent = 'BGM OFF';
            if (bgm) bgm.pause();
        }
    }

    // ★ 復元された goToSlide 関数
    function goToSlide(index, userAction = false) {
        document.body.classList.add('started');
        if (startOverlay && !startOverlay.classList.contains('hidden')) {
            startOverlay.classList.add('hidden');
        }

        // コマを選んだ際、BGM設定がONなら音楽を流す/維持する
        if (isBgmEnabled) {
            tryPlayBGM();
        }

        slides[currentSlide].classList.remove('active');
        if (pageBtns[currentSlide]) pageBtns[currentSlide].classList.remove('active');

        currentSlide = index;

        slides[currentSlide].classList.add('active');
        if (pageBtns[currentSlide]) pageBtns[currentSlide].classList.add('active');

        const month = parseInt(slides[currentSlide].getAttribute('data-month')) || 0;
        const maxMonth = 6;
        const percent = (month / maxMonth) * 100;

        baby.style.left = `${percent}%`;
        progress.style.width = `${percent}%`;

        // プロフィールのぽわん演出をリセット＆リスタート
        const activeSlide = slides[currentSlide];
        activeSlide.classList.remove('active');
        void activeSlide.offsetWidth; // リフロー発生
        activeSlide.classList.add('active');

        // 自動再生中ならタイマーをリフレッシュして継続
        if (isAuto) {
            startAutoSlide();
        }
    }

    function nextSlide(userAction = false) {
        let nextIndex = (currentSlide + 1) % slides.length;
        goToSlide(nextIndex, userAction);
    }

    function prevSlide(userAction = false) {
        let prevIndex = (currentSlide - 1 + slides.length) % slides.length;
        goToSlide(prevIndex, userAction);
    }

    function toggleMode() {
        document.body.classList.add('started');
        if (startOverlay && !startOverlay.classList.contains('hidden')) {
            startOverlay.classList.add('hidden');
        }
        setAutoMode(!isAuto);
    }

    function setAutoMode(enableAuto) {
        isAuto = enableAuto;
        
        if (isAuto) {
            modeBtn.classList.add('active');
            modeIcon.textContent = '⏸';
            modeText.textContent = 'STOP';
            
            document.body.classList.remove('paused');
            baby.classList.remove('paused');
            
            if (isBgmEnabled) tryPlayBGM();

            const activeSlide = slides[currentSlide];
            activeSlide.classList.remove('active');
            void activeSlide.offsetWidth;
            activeSlide.classList.add('active');

            startAutoSlide();
        } else {
            modeBtn.classList.remove('active');
            modeIcon.textContent = '▶';
            modeText.textContent = 'AUTO PLAY';
            
            document.body.classList.add('paused');
            baby.classList.add('paused');
            
            // STOPボタンが押された時は音楽を停止
            if (bgm) bgm.pause();

            stopAutoSlide();
        }
    }

    function startAutoSlide() {
        stopAutoSlide();
        autoTimeoutId = setTimeout(() => {
            nextSlide(false);
        }, SLIDE_DURATION);
    }

    function stopAutoSlide() {
        if (autoTimeoutId) {
            clearTimeout(autoTimeoutId);
            autoTimeoutId = null;
        }
    }
</script>

